"""Keeps the Claude Code entry of each portal-assistant skill in step with the skill itself.

The skills live in the standalone project (portal_assistant/skills/<name>/SKILL.md, owner
2026-11-24); Claude Code discovers skills under the repository's .claude/skills/. This
script writes .claude/skills/<name>/SKILL.md for every skill: the same front matter (name,
description) and a body that sends the agent to the full skill, so there is one text to edit.

    python -X utf8 portal_assistant/scripts/sync_skill.py           # write
    python -X utf8 portal_assistant/scripts/sync_skill.py --check   # exit 1 when out of step
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent      # portal_assistant/
REPO = ROOT.parent
SKILLS = ROOT / "skills"
ENTRY = REPO / ".claude" / "skills"
FRONT = re.compile(r"\A---\n(.*?)\n---\n", re.S)


def entry_text(skill):
    source = skill.read_text(encoding="utf-8").replace("\r\n", "\n")
    front = FRONT.match(source)
    if not front:
        raise SystemExit(f"{skill}: no front matter")
    relative = skill.relative_to(REPO).as_posix()
    return (f"---\n{front.group(1)}\n---\n\n"
            f"<!-- Generated by portal_assistant/scripts/sync_skill.py from {relative}. Edit that file. -->\n\n"
            f"This skill lives in the standalone assistant project. Read `{relative}` in full and follow it step by "
            f"step (its templates are in the same folder). Read `AGENTS.md` and "
            f"`portal_assistant/docs/AI_CURRENT_RULES.md` first.\n\n"
            f"本 skill 的正文在 `{relative}`：完整讀過再照著一步步做（範本在同一個資料夾）；先讀 `AGENTS.md` 與 "
            f"`portal_assistant/docs/AI_CURRENT_RULES.md`。\n")


def expected():
    return {ENTRY / skill.parent.name / "SKILL.md": entry_text(skill) for skill in sorted(SKILLS.glob("*/SKILL.md"))}


def main():
    check = "--check" in sys.argv
    files = expected()
    stale = [path for path, text in files.items()
             if not path.exists() or path.read_text(encoding="utf-8").replace("\r\n", "\n") != text]
    extra = [p for p in ENTRY.glob("*/SKILL.md") if p not in files and "sync_skill.py" in p.read_text(encoding="utf-8")]
    if check:
        for path in stale + extra:
            print(f"{path.relative_to(REPO).as_posix()}: out of step (run portal_assistant/scripts/sync_skill.py)")
        print(f"{len(files)} skill(s), {len(stale) + len(extra)} out of step")
        return 1 if stale or extra else 0
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(files[path], encoding="utf-8")
        print(f"wrote {path.relative_to(REPO).as_posix()}")
    for path in extra:
        path.unlink()
        print(f"removed {path.relative_to(REPO).as_posix()} (its skill is gone)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
